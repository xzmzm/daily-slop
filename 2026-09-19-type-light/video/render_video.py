def original_music(path: Path, seconds: float):
    """Original C-major-seventh ambient study; no samples or licensed assets."""
    rate = 22050
    chord = [130.8128, 164.8138, 195.9977]
    melody = [261.6256, 329.6276, 391.9954, 493.8833, 523.2511, 391.9954, 329.6276, 293.6648]
    with wave.open(str(path),'wb') as output:
        output.setnchannels(1);output.setsampwidth(2);output.setframerate(rate)
        for start in range(0, round(seconds*rate), rate):
            values = array.array('h')
            for i in range(start, min(start+rate,round(seconds*rate))):
                t=i/rate
                fade=min(1,t/2,max(0,(seconds-t)/3))
                pad=sum(math.sin(2*math.pi*f*t+.18*math.sin(t*.3+j)) for j,f in enumerate(chord))*.019
                phase=t%1.5
                note=math.sin(2*math.pi*melody[int(t/1.5)%len(melody)]*phase)*math.exp(-phase*4)*min(1,phase*80)*.055
                values.append(round((pad+note)*fade*32767))
            if sys.byteorder!='little':values.byteswap()
            output.writeframes(values.tobytes())


