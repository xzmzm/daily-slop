def capture_video(output: Path, work: Path, audio: Path, durations: list[float], narrated: bool, inline: bool, limit: float | None):
    seconds=sum(durations)+(len(durations)-1)*SILENCE_BETWEEN+SILENCE_TAIL
    if limit is not None:seconds=min(seconds,limit)
    cues=base.caption_cues(durations)
    base.write_srt(output.with_suffix('.srt'),durations)
    command=['ffmpeg','-hide_banner','-loglevel','error','-y','-f','image2pipe','-framerate',str(FPS),'-i','pipe:0','-i',str(audio),'-t',f'{seconds:.3f}','-c:v','libx264','-preset','medium','-crf','20','-pix_fmt','yuv420p','-c:a','aac','-b:a','128k','-movflags','+faststart',str(output)]
    errors=[]
    with (work/'ffmpeg.log').open('w') as log, serve() as port, sync_playwright() as p:
        browser=launch(p)
        context=browser.new_context(viewport={'width':1600,'height':900},device_scale_factor=1.2,accept_downloads=True)
        page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
        page.clock.install(time=0);page.clock.pause_at(0)
        load_page(page,port,inline);decorate(page,narrated);page.clock.run_for(100)
        encoder=subprocess.Popen(command,stdin=subprocess.PIPE,stderr=log)
        frame=0;position=(1505.,810.);base.set_cursor(page,position)
        max_frames=round(seconds*FPS)
        def capture(clicking=False):
            nonlocal frame
            if frame>=max_frames:return
            page.clock.run_for(round((frame+1)*1000/FPS)-round(frame*1000/FPS))
            page.evaluate('(text)=>document.getElementById("video-caption").textContent=text',base.caption_at(frame/FPS,cues))
            base.set_cursor(page,position,clicking)
            encoder.stdin.write(page.screenshot(type='png'))
            frame+=1
        def hold(until):
            while frame<min(round(until*FPS),max_frames):capture()
        def move(target):
            nonlocal position
            start=position;dx=target[0]-start[0];dy=target[1]-start[1];length=max(1,math.hypot(dx,dy))
            for i in range(9):
                u=i/8;e=u*u*(3-2*u);arc=math.sin(math.pi*e)*min(12,length*.025)
                position=(start[0]+dx*e-dy/length*arc,start[1]+dy*e+dx/length*arc);capture()
            hold(frame/FPS+.15)
        def control(selector,value=None):
            box=page.locator(selector).bounding_box();move((box['x']+box['width']/2,box['y']+box['height']/2))
            if value is None:page.locator(selector).click()
            else:page.locator(selector).select_option(value)
            capture(True)
        def drag(selector,target):
            nonlocal position
            el=page.locator(selector);box=el.bounding_box()
            lo=float(el.get_attribute('min'));hi=float(el.get_attribute('max'));value=float(el.input_value())
            x=lambda v:box['x']+5+(box['width']-10)*(v-lo)/(hi-lo)
            y=box['y']+box['height']/2;move((x(value),y));page.mouse.move(*position);page.mouse.down()
            for i in range(13):
                u=i/12;e=u*u*(3-2*u);position=(x(value+(target-value)*e),y);page.mouse.move(*position);capture(True)
            page.mouse.up();capture()
        end=0.
        try:
            for scene,span in enumerate(durations):
                if frame>=max_frames:break
                end+=span+(SILENCE_BETWEEN if scene<len(durations)-1 else SILENCE_TAIL)
                if scene==1:
                    control('#play');drag('#reveal',0)
                elif scene==2:
                    control('#source','signal');control('#charset','binary')
                elif scene==3:control('#dither','ordered')
                elif scene==4:
                    control('#dither','diffusion');hold(end-7);drag('#columns',48);hold(end-3);drag('#columns',132)
                elif scene==5:
                    control('#source','knot');control('#play');control('#charset','classic');control('#dither','none');control('[data-palette="amber"]');hold(end-4);control('[data-palette="paper"]')
                elif scene==6:
                    control('[data-palette="color"]');control('#play');hold(end-6)
                    if not inline:control('#save-text')
                hold(end)
                print(f'Captured scene {scene+1}/{len(durations)}: {frame/FPS:.1f}s',flush=True)
        finally:
            encoder.stdin.close();result=encoder.wait(timeout=120);browser.close()
        if result:raise RuntimeError(f'ffmpeg failed; see {work/"ffmpeg.log"}')
    if errors:raise RuntimeError('Browser capture errors: '+repr(errors))
    return seconds


def gallery_shot(inline: bool):
    with serve() as port,sync_playwright() as p:
        browser=launch(p);page=browser.new_page(viewport={'width':1280,'height':800},device_scale_factor=1)
        load_page(page,port,inline);page.locator('#play').click();page.evaluate('typeLight.renderAt(1.7)')
        data=page.screenshot(type='png');browser.close()
    out=ROOT_DIR/'gallery/shots'/f'{PROJECT.name}.png';out.parent.mkdir(parents=True,exist_ok=True)
    Image.open(io.BytesIO(data)).resize((800,500),Image.Resampling.LANCZOS).save(out)


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--inline',action='store_true')
    parser.add_argument('--captions-only',action='store_true')
    parser.add_argument('--skip-gallery',action='store_true')
    parser.add_argument('--max-seconds',type=float)
    parser.add_argument('--output',type=Path,default=PROJECT/'video/type-light.mp4')
    args=parser.parse_args();output=args.output.resolve();output.parent.mkdir(parents=True,exist_ok=True)
    if args.max_seconds is not None and args.max_seconds<=0:parser.error('--max-seconds must be positive')
    work=Path(tempfile.mkdtemp(prefix='type-light-video-build-'))
    print(f'Work directory: {work}',flush=True)
    audio,durations,audio_info=audio_track(work,args.captions_only)
    print(f'Audio mode: {audio_info["mode"]}',flush=True)
    seconds=capture_video(output,work,audio,durations,audio_info['mode']=='chinese-narration',args.inline,args.max_seconds)
    metadata={'project':PROJECT.name,'built_by':'GPT-6 Astra','resolution':[WIDTH,HEIGHT],'fps':FPS,'duration_seconds':duration(output),'demo_url':URL,'capture':'real local browser UI with deterministic Playwright clock','audio':audio_info,'segment_durations':durations,'preview':args.max_seconds is not None}
    output.with_suffix('.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    if not args.skip_gallery:
        gallery_shot(args.inline)
        subprocess.run([sys.executable,str(ROOT_DIR/'tools/build_gallery.py'),'--no-shots'],check=True,cwd=ROOT_DIR)
    subprocess.run(['ffmpeg','-v','error','-i',str(output),'-f','null','-'],check=True)
    print(json.dumps(metadata,ensure_ascii=False,indent=2),flush=True)
    # Work directories are retained for diagnosis, never recursively deleted.

if __name__=='__main__':main()
